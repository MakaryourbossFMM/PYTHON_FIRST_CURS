# Авиакомпания пускает сумку в салон, если её длина не больше 55 см, ширина не больше 40 см,
# высота не больше 20 см, а вес не больше 10 кг. Вводятся длина, ширина и высота — целые числа,
# затем вес — дробное число. Выведите «Можно взять в салон» или «Нужно сдать в багаж».
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     50
#     35
#     20
#     7.5
#   в терминале:
#     Длина, см: 50
#     Ширина, см: 35
#     Высота, см: 20
#     Вес, кг: 7.5
#     Можно взять в салон
# Пример 2
#   ввод:
#     56
#     35
#     20
#     5
#   в терминале:
#     Длина, см: 56
#     Ширина, см: 35
#     Высота, см: 20
#     Вес, кг: 5
#     Нужно сдать в багаж
# Пример 3
#   ввод:
#     40
#     30
#     15
#     10.0
#   в терминале:
#     Длина, см: 40
#     Ширина, см: 30
#     Высота, см: 15
#     Вес, кг: 10.0
#     Можно взять в салон
# Пример 4
#   ввод:
#     40
#     30
#     15
#     10.5
#   в терминале:
#     Длина, см: 40
#     Ширина, см: 30
#     Высота, см: 15
#     Вес, кг: 10.5
#     Нужно сдать в багаж

# Решение
length = int(input("Длина, см: "))
width = int(input("Ширина, см: "))
height = int(input("Высота, см: "))
weight = float(input("Вес, кг: "))

if length <= 55 and width <= 40 and height <= 20 and weight <= 10:
    print("Можно взять в салон")
else:
    print("Нужно сдать в багаж")
    